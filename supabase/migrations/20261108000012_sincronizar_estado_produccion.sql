-- ── Analítica propia: visitas y clics, sin cookies ni datos personales ──
create table if not exists public.site_events (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  event text not null,
  path text not null,
  referrer_host text,
  utm_source text,
  utm_medium text,
  utm_campaign text,
  from_ads boolean not null default false,
  device text
);

create index if not exists site_events_created_idx on public.site_events (created_at desc);
create index if not exists site_events_event_path_idx on public.site_events (event, path, created_at desc);

alter table public.site_events enable row level security;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'site_events' and policyname = 'site_events_select_admin'
  ) then
    create policy site_events_select_admin on public.site_events
      for select to authenticated using (public.is_admin());
  end if;
end $$;

create or replace function public.track_site_event(
  p_event text,
  p_path text,
  p_referrer_host text default null,
  p_utm_source text default null,
  p_utm_medium text default null,
  p_utm_campaign text default null,
  p_from_ads boolean default false,
  p_device text default null
) returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_path text;
begin
  if p_event is null or p_event not in ('view','call','whatsapp','form') then
    return;
  end if;
  -- Solo ruta, sin parámetros ni fragmentos; se ignora el panel interno y rutas absurdas.
  v_path := split_part(split_part(coalesce(p_path, ''), '?', 1), '#', 1);
  if v_path !~ '^/[A-Za-z0-9/_\-\.]{0,198}$' or v_path like '/admin%' then
    return;
  end if;
  insert into public.site_events
    (event, path, referrer_host, utm_source, utm_medium, utm_campaign, from_ads, device)
  values (
    p_event,
    v_path,
    nullif(left(p_referrer_host, 120), ''),
    nullif(left(p_utm_source, 100), ''),
    nullif(left(p_utm_medium, 100), ''),
    nullif(left(p_utm_campaign, 100), ''),
    coalesce(p_from_ads, false),
    case when p_device in ('mobile','tablet','desktop') then p_device end
  );
end;
$$;

create or replace function public.analytics_by_day(p_days integer default 30)
returns table(day date, path text, event text, n bigint)
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception 'No autorizado' using errcode = '42501';
  end if;
  return query
    select (e.created_at at time zone 'Europe/Madrid')::date as day, e.path, e.event, count(*)::bigint
    from public.site_events e
    where e.created_at >= now() - make_interval(days => greatest(1, least(coalesce(p_days, 30), 365)))
    group by 1, 2, 3
    order by 1 desc, 2, 3;
end;
$$;

create or replace function public.analytics_by_source(p_days integer default 30)
returns table(source text, from_ads boolean, path text, event text, n bigint)
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception 'No autorizado' using errcode = '42501';
  end if;
  return query
    select coalesce(e.utm_campaign, e.utm_source, e.referrer_host, 'directo') as source,
           e.from_ads, e.path, e.event, count(*)::bigint
    from public.site_events e
    where e.created_at >= now() - make_interval(days => greatest(1, least(coalesce(p_days, 30), 365)))
    group by 1, 2, 3, 4
    order by 5 desc;
end;
$$;

-- ── Aviso por correo de cada solicitud nueva (formulario y citas) ──
create extension if not exists pg_net;

create or replace function public.notify_new_contact_request()
returns trigger
language plpgsql
security definer
set search_path = public, extensions, net
as $$
begin
  -- Aviso por correo: nunca debe impedir que la fila se guarde
  begin
    perform net.http_post(
      url := 'https://nwcfklphajyukgldrwrh.supabase.co/functions/v1/notify-contact-request',
      body := jsonb_build_object('id', new.id, 'table', tg_table_name),
      headers := jsonb_build_object('Content-Type', 'application/json'),
      timeout_milliseconds := 5000
    );
  exception when others then
    raise warning 'notify_new_contact_request: %', sqlerrm;
  end;
  return new;
end;
$$;

drop trigger if exists contact_requests_notify on public.contact_requests;
create trigger contact_requests_notify
  after insert on public.contact_requests
  for each row execute function public.notify_new_contact_request();

drop trigger if exists appointments_notify on public.appointments;
create trigger appointments_notify
  after insert on public.appointments
  for each row execute function public.notify_new_contact_request();
